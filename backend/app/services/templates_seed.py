def seed_templates(session: Session) -> dict[str, int]:
    inserted = 0
    updated = 0
    for index, data in enumerate(TEMPLATES):
        template = session.scalar(select(Template).where(Template.slug == data["slug"]))
        if template is None:
            template = Template(**data, sort_order=index)
            session.add(template)
            inserted += 1
        else:
            for key, value in data.items():
                setattr(template, key, value)
            template.sort_order = index
            updated += 1
    session.commit()
    return {"inserted": inserted, "updated": updated}
